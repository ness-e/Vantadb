// ------------------------------------------------------------------- parsing

function sectionLines(text, header) {
  const lines = String(text).split("\n");
  const start = lines.findIndex((l) => l.trim() === header);
  if (start === -1) return null;
  const out = [];
  for (let i = start + 1; i < lines.length; i++) {
    if (/^\[.*\]/.test(lines[i].trim())) break;
    out.push(lines[i]);
  }
  return out;
}

function parseWorkspaceVersion(cargoToml) {
  const lines = sectionLines(cargoToml, "[workspace.package]");
  if (!lines) return null;
  for (const line of lines) {
    const m = line.trim().match(/^version\s*=\s*"([^"]+)"/);
    if (m) return m[1];
  }
  return null;
}

function parseListField(sectionText, field) {
  // members = [ "...", ... ] possibly spanning lines, with # comments
  const noComments = String(sectionText)
    .split("\n")
    .map((l) => l.split("#")[0])
    .join("\n");
  const m = noComments.match(new RegExp(field + "\\s*=\\s*\\[([^\\]]*)\\]", "s"));
  if (!m) return [];
  return m[1]
    .split(",")
    .map((s) => s.trim().replace(/^"|"$/g, ""))
    .filter(Boolean);
}

function readText(path) {
  try {
    return readFileSync(abs(path), "utf8");
  } catch {
    return null;
  }
}

function parsePackageManifest(text) {
  // [package] name / version / publish — first occurrence wins (this repo's
  // manifests keep exactly one [package] section each).
  const name = (text.match(/^name\s*=\s*"([^"]+)"/m) || [])[1] || null;
  const versionLine = text.match(/^version(\.workspace)?\s*=\s*(.+)$/m) || [];
  const publish = (text.match(/^publish\s*=\s*(.+)$/m) || [])[1]?.trim() || null;
  return {
    name,
    versionLine: versionLine[0] || null,
    inherits: versionLine[0]?.includes("workspace") || false,
    publish,
  };
}

function parseReleasePlz(text) {
  // [[package]] name="x" ... release = false — collected per block
  const out = {};
  const blocks = String(text).split("[[package]]").slice(1);
  for (const b of blocks) {
    const name = (b.match(/^\s*name\s*=\s*"([^"]+)"/m) || [])[1];
    if (!name) continue;
    const rel = (b.match(/^\s*release\s*=\s*(true|false)/m) || [])[1];
    if (rel) out[name] = rel;
  }
  return out;
}

function parseNpmVersion(text) {
  try {
    const v = JSON.parse(text)?.version;
    return typeof v === "string" && v.length ? v : null;
  } catch {
    return null;
  }
}

// -------------------------------------------------------------------- gather

function failHard(message) {
  console.error(`DEGRADED (exit 2): ${message}`);
  console.error("  This is NOT a pass — the gate could not be evaluated.");
  process.exit(2);
}

function gather() {
  const rootToml = readText("Cargo.toml");
  if (!rootToml) failHard("Cargo.toml is not readable");
  const workspace = parseWorkspaceVersion(rootToml);
  if (!workspace) failHard("no [workspace.package] version in Cargo.toml");
  const wsSection = (sectionLines(rootToml, "[workspace]") || []).join("\n");
  const members = parseListField(wsSection, "members");
  if (!members.length) failHard("no [workspace] members parsed");
  const releasePlz = parseReleasePlz(readText("release-plz.toml") || "");

  const rows = [];
  const problems = [];
  const seen = new Set();

  const pushRow = (path, name, version, status, why, channel, tag) => {
    rows.push({ path, name, version, status, why, channel, tag });
    seen.add(path);
  };

  for (const m of members) {
    const manifest = readText(m === "." ? "Cargo.toml" : `${m}/Cargo.toml`);
    if (!manifest) {
      problems.push(`${m}: workspace member without readable Cargo.toml`);
      continue;
    }
    const pkg = parsePackageManifest(manifest);
    if (!pkg.name) {
      problems.push(`${m}: no [package] name parsed`);
      continue;
    }
    const entry = STATUS_OVERRIDES[m];
    if (!entry) {
      problems.push(
        `${m} (${pkg.name}): NEEDS-TRIAGE — no STATUS_OVERRIDES entry; declare PUBLIC/INTERNAL/EXPERIMENTAL/FROZEN/RETIRED in gen-surface-manifest.mjs`,
      );
      pushRow(
        m,
        pkg.name,
        pkg.inherits ? `${workspace} (workspace)` : pkg.versionLine || "unknown",
        "NEEDS-TRIAGE",
        "undeclared — triage required, must never pass silently",
        "—",
        TAG_NS[m] || "—",
      );
      continue;
    }
    const version = pkg.inherits
      ? `${workspace} (workspace)`
      : pkg.versionLine
        ? pkg.versionLine.replace(/^version\s*=\s*/, "")
        : "unknown";
    const channel =
      releasePlz[pkg.name] === "false"
        ? "release-plz `release = false`"
        : pkg.publish === "false"
          ? "`publish = false` (non-crates.io channel)"
          : "crates.io (release-plz managed)";
    pushRow(m, pkg.name, version, entry[0], entry[1], channel, TAG_NS[m] || "—");
  }

  // Non-member distributables with their own manifests (declared, not derived).
  const nodeManifest = readText("vantadb-node/package.json");
  if (nodeManifest && !seen.has("vantadb-node")) {
    const entry = STATUS_OVERRIDES["vantadb-node"];
    pushRow(
      "vantadb-node",
      "vantadb-node (npm)",
      parseNpmVersion(nodeManifest) || "unreadable",
      entry[0],
      entry[1],
      "npm (planned; `release-npm-node.yml`)",
      TAG_NS["vantadb-node"] || "—",
    );
  }
  for (const extra of ["providers/openai", "providers/ollama", "providers/litellm", "fuzz"]) {
    if (seen.has(extra)) continue;
    const manifest = readText(`${extra}/Cargo.toml`);
    const entry = STATUS_OVERRIDES[extra];
    const name = manifest ? parsePackageManifest(manifest).name || extra : extra;
    const version = manifest
      ? parsePackageManifest(manifest).inherits
        ? `${workspace} (workspace)`
        : "see manifest"
      : "n/a (no crate manifest)";
    if (!entry) {
      problems.push(`${extra}: NEEDS-TRIAGE — no STATUS_OVERRIDES entry`);
      continue;
    }
    pushRow(
      extra,
      name,
      version,
      entry[0],
      entry[1],
      manifest ? "`publish = false` (non-crates.io channel)" : "n/a",
      TAG_NS[extra] || "—",
    );
  }

  // Stale declarations (override without a surface) are contradictions too.
  for (const key of Object.keys(STATUS_OVERRIDES)) {
    if (!seen.has(key))
      problems.push(`${key}: stale STATUS_OVERRIDES entry — surface no longer exists (remove it)`);
  }

  // npm / python version dimension (REL-03): derived, never duplicated.
  const tsV = parseNpmVersion(readText("vantadb-ts/package.json"));
  const nodeV = parseNpmVersion(readText("vantadb-node/package.json"));
  const pyproject = readText("vantadb-python/pyproject.toml") || "";
  const pyDynamic = /dynamic\s*=\s*\["version"\]/.test(pyproject);
  const versions = [
    { surface: "workspace (Rust crates)", found: workspace, expected: workspace, ok: true },
    {
      surface: "`vantadb` (npm, vantadb-ts)",
      found: tsV,
      expected: workspace,
      ok: tsV === workspace,
    },
    {
      surface: "`vantadb-node` (npm, never-published allowance 0.7.0)",
      found: nodeV,
      expected: workspace,
      ok: nodeV === workspace || nodeV === "0.7.0",
    },
    {
      surface: "`vantadb-py` (maturin dynamic version)",
      found: pyDynamic ? `dynamic → ${workspace}` : "STATIC (drift risk)",
      expected: `dynamic → ${workspace}`,
      ok: pyDynamic,
    },
  ];
  for (const v of versions) {
    if (!v.ok) problems.push(`${v.surface}: version ${v.found} != expected ${v.expected}`);
  }

  return { workspace, rows, versions, problems };
}

// -------------------------------------------------------------------- render

function render({ workspace, rows, versions }) {
  const L = [];
  L.push("---");
  L.push('title: "Public Surface Manifest"');
  L.push("kind: reference");
  L.push('description: "Generated inventory of every public surface with status and version"');
  L.push("tags: [vantadb, surface, release]");
  L.push("---");
  L.push("");
  L.push(
    "<!-- GENERATED by node scripts/docs/gen-surface-manifest.mjs --write — do not hand-edit. -->",
  );
  L.push("");
  L.push("# Public Surface Manifest");
  L.push("");
  L.push(
    `> **workspace version: ${workspace}** (source: root \`Cargo.toml\` \`[workspace.package]\`).`,
  );
  L.push("> Status per surface is declared once in `STATUS_OVERRIDES` inside the generator;");
  L.push("> versions, members, publish flags and release-plz overrides are derived mechanically.");
  L.push(
    "> Consolidates (by reference, never by copy) the binding taxonomy, the DIST-06 crate table, and the release taxonomy:",
  );
  L.push(
    "> [BINDINGS_NAMESPACES.md](./BINDINGS_NAMESPACES.md) · `docs/dev/workflow/PUBLISH.md` (DIST-06, tag namespaces) · taxonomy in `.opencode/AGENTS.md`.",
  );
  L.push(
    "> This manifest does not resolve Backlog-vs-ADR-vs-code contradictions — it makes them detectable (deviations become `FIND-*` rows).",
  );
  L.push("");
  L.push("## Surfaces");
  L.push("");
  L.push("| Surface (path) | Crate / package | Version | Status | Channel | Tag namespace | Why |");
  L.push("|---|---|---|---|---|---|---|");
  for (const r of rows) {
    L.push(
      `| \`${r.path}\` | \`${r.name}\` | ${r.version} | **${r.status}** | ${r.channel} | ${r.tag} | ${r.why} |`,
    );
  }
  L.push("");
  L.push("## Versions (REL-03 — generated, not manual)");
  L.push("");
  L.push("| Surface | Found | Expected |");
  L.push("|---|---|---|");
  for (const v of versions) {
    L.push(`| ${v.surface} | ${v.found} | ${v.expected} |`);
  }
  L.push("");
  L.push(
    "Gates: `node scripts/docs/check-npm-versions.mjs` (npm) + `tests/version_coherence.rs` (Rust surfaces + this manifest).",
  );
  L.push("");
  L.push("## Authority map (DOC-22 — concept to canonical source)");
  L.push("");
  L.push("| Concept | Canonical source (everything else only references) |");
  L.push("|---|---|");
  for (const [concept, source] of AUTHORITY) {
    L.push(`| ${concept} | ${source} |`);
  }
  L.push("");
  return L.join("\n");
}

// ---------------------------------------------------------------------- main

const ARGS = process.argv.slice(2);
const WRITE = ARGS.includes("--write");
const CHECK = ARGS.includes("--check");

const data = gather();
const out = render(data);

if (data.problems.length) {
  for (const p of data.problems) console.error(`GATE FAILED: ${p}`);
  console.error("");
  console.error(
    "How to fix: declare the surface in STATUS_OVERRIDES (same PR), or fix the version drift.",
  );
  process.exit(1);
}

if (CHECK) {
  const current = readText(OUT);
  if (current !== out) {
    console.error(
      `GATE FAILED: ${OUT} is stale — run \`node scripts/docs/gen-surface-manifest.mjs --write\` and commit the diff.`,
    );
    process.exit(1);
  }
  console.log(`OK: ${OUT} in sync (workspace ${data.workspace}, ${data.rows.length} surfaces).`);
  process.exit(0);
}

if (WRITE) {
  writeFileSync(abs(OUT), out);
  console.log(`WROTE ${OUT} (${data.rows.length} surfaces, workspace ${data.workspace}).`);
  process.exit(0);
}

console.log(out);
