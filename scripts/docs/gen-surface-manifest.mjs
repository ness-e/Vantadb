//
// PURPOSE
//   SURF-01 (+ slices DOC-22, REL-03): generate docs/api/SURFACE_MANIFEST.md —
//   one mechanical inventory of every public surface (crate / npm package /
//   python binding / workflow channel / CLI / API / feature / doc) with its
//   PUBLIC / INTERNAL / EXPERIMENTAL / FROZEN / RETIRED status and version.
//   Consolidates (links, never duplicates) docs/api/BINDINGS_NAMESPACES.md,
//   the DIST-06 crate table in docs/dev/workflow/PUBLISH.md, and the taxonomy
//   in .opencode/AGENTS.md.
//
//   What is DERIVED (fail-closed): workspace members, per-crate version and
//   `publish` flag, release-plz overrides, npm manifest versions, python
//   dynamic-version invariant. What is DECLARED: the STATUS_OVERRIDES table
//   below (one visible place) + the AUTHORITY map (DOC-22) + the TAG_NS mirror
//   of PUBLISH.md. If a member has no status entry the gate FAILS (exit 1) —
//   an undeclared surface must never pass silently (same fail-closed policy as
//   check-npm-versions.mjs). The manifest does NOT resolve Backlog-vs-ADR-vs-
//   code contradictions (e.g. MEMG-05/MEMG-09): it makes them detectable —
//   deviations become FIND-* rows.
//
// WHERE IT RUNS
//   Locally:  node scripts/docs/gen-surface-manifest.mjs --write [--check]
//   CI:       gate-docs.yml (via --check), version_coherence.rs (content sync)
//
// USAGE / EXIT CODES
//   --write  regenerate docs/api/SURFACE_MANIFEST.md
//   --check  exit 1 when the checked-in manifest differs from generated output
//            or when a surface lacks a declared status (NEEDS-TRIAGE)
//   (no flags) prints the manifest to stdout (dry run)
//   0 = ok · 1 = gate failed · 2 = cannot evaluate (not a pass)

