#!/usr/bin/env node
// scripts/docs/check-api-docs.mjs
//
// PURPOSE
//   Fails the build when the PUBLIC API SURFACE changes and no documentation
//   changes with it. The pattern is DuckDB's `NeedsDocumentation.yml`; the rule
//   is one line: an API change with a zero-line doc diff is drift.
//
// WHY THIS EXISTS (verified, 2026-09-29)
//   `llms.txt` publishes `db.search_memory()` — a method that does not exist.
//   `docs/api/PYTHON_SDK.md` documents a `VantaError` exception (the real one is
//   `Error`) and its Quick Start calls `.get()` on something that returns a list.
//   Nothing in CI noticed. Every other docs gate in scripts/docs/ checks that
//   documents are WELL FORMED. None of them check that they are TRUE.
//
// WHAT IS COMPARED
//   A normalized `lang \t kind \t name` fingerprint. Names and kinds only — no
//   signatures, no bodies. A signature change is owned by the existing
//   `tests/api/public_api.rs` snapshot (cargo public-api, nightly) in
//   `public-api-snapshot`; this gate owns the cheap lane and does not overlap it.
//
// HOW EACH SURFACE IS READ (no dependency, no build, no network)
//   rust  - static parse of `src/lib.rs`: `pub mod` reachable transitively,
//           top-level `pub fn|struct|enum|trait|type|const`, inherent
//           `impl T { pub fn }` methods, and the crate-root `pub use` re-exports.
//   python- `.pyi` type stubs + the `__all__` re-export lists. The stubs are the
//           DECLARED surface and `vantadb-python/tests/test_stub_drift.py`
//           already asserts they match the compiled module via
//           `inspect.signature`, so reading the stub is reading the surface.
//   ts    - static parse of `vantadb-ts/src/*.ts` (`export` decls, class
//           members, interface members, object-literal properties).
//
// NOT CHECKED (see docs/dev/workflow/gate-api-docs.md)
//   Signature changes, behaviour changes, semantic accuracy, doc QUALITY.
//   This gate cannot tell a good doc diff from a cosmetic one; it only
//   measures whether one exists.
//
// USAGE
//   node scripts/docs/check-api-docs.mjs --self-test
//   node scripts/docs/check-api-docs.mjs --api-surface              # working tree
//   node scripts/docs/check-api-docs.mjs --api-surface HEAD
//   node scripts/docs/check-api-docs.mjs --api-surface HEAD --json
//   node scripts/docs/check-api-docs.mjs --changed origin/main..HEAD
//   node scripts/docs/check-api-docs.mjs --changed origin/main..WORKTREE
//   node scripts/docs/check-api-docs.mjs --changed A..B --max-undocumented=3
//
//   --api-surface [ref]  emit the fingerprint and exit 0 (2 if the ref is bad)
//   --changed <a>..<b>   gate. `WORKTREE` compares against uncommitted files
//   --json               machine-readable
//   --max-undocumented=N surface changes tolerated with NO doc diff (default 0)
//   --max-llms-stale=N   surface changes tolerated when docs/ moved but
//                        llms.txt did not (default 0)
//   --self-test          built-in assertions on synthetic fixtures
//
// EXIT CODES
//   0 = surface unchanged, or changed with docs that moved with it
//   1 = GATE FAILED (see which budget, and why)
//   2 = bad usage / unreadable ref
//   3 = DEGRADED — the comparison could not be evaluated (git missing, ref not
//       fetched). Deliberately distinct from 1: a gate that cannot prove
//       anything must not be reported as if it passed.

import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, sep } from 'node:path';
import { abs, ROOT } from './lib.mjs';

const toPosix = (p) => p.split(sep).join('/');

// --------------------------------------------------------------------- config

/**
 * Budgets. Two, not one, because they are two different failures with two
 * different fixes: "you changed the API and wrote nothing" is fixed by writing,
 * "you wrote docs but did not regenerate llms.txt" is fixed by running the
 * generator. One number for both would force you to raise the other to work
 * around this one — which is how budgets stop being budgets.
 *
 * Both default to 0. A gate that starts red gets switched off, so the defaults
 * are the strict ones; if this repo ever needs slack, raise one with the flag
 * and date the reason, the way check-links.mjs does.
 */
const UNDOCUMENTED_BUDGET = numFlag('--max-undocumented=', 0);
const LLMS_STALE_BUDGET = numFlag('--max-llms-stale=', 0);

function numFlag(name, dflt) {
  const raw = process.argv.find((a) => a.startsWith(name));
  if (!raw) return dflt;
  const n = Number(raw.slice(name.length));
  return Number.isFinite(n) ? n : dflt;
}

