const ARGS = process.argv.slice(2);
const JSON_OUT = ARGS.includes('--json');

function printSurface(surface, note) {
  const total = surfaceSize(surface);
  const lines = [];
  for (const { id, label } of LANGUAGES) {
    const entries = surface.get(id) ?? [];
    lines.push(`${(label + ' surface').padEnd(21)}: ${entries.length}`);
    if (JSON_OUT) continue;
    const byKind = new Map();
    for (const e of entries) {
      const k = e.split('\t')[1];
      byKind.set(k, (byKind.get(k) ?? 0) + 1);
    }
    const kinds = [...byKind].sort((a, b) => b[1] - a[1]);
    lines.push(
      `${''.padEnd(21)}  ${kinds.map(([k, n]) => `${k} ${n}`).join('  ')}`,
    );
  }
  lines.push(`${'total'.padEnd(21)}: ${total}`);
  if (note) lines.push(`ref${' '.repeat(17)}: ${note}`);
  return lines;
}

function reportSurface(refArg) {
  const ref = new Ref(refArg);
  if (!ref.worktree && !gitRefExists(ref.ref)) {
    console.error(`error: ref "${ref.ref}" is not resolvable in this repository.`);
    console.error('       Fetch it first:  git fetch --no-tags --depth=1 origin ' + ref.ref);
    process.exit(2);
  }
  const surface = buildSurface(ref.reader);
  if (JSON_OUT) {
    console.log(JSON.stringify(Object.fromEntries(surface), null, 2));
  } else {
    console.log(printSurface(surface, ref.label).join('\n'));
    if (surfaceSize(surface) === 0) {
      console.error('\nerror: empty surface — the paths read did not exist at this ref.');
      process.exit(2);
    }
  }
  process.exit(0);
}

function gitRefExists(r) {
  try {
    execFileSync('git', ['rev-parse', '--verify', '--quiet', `${r}^{commit}`], { stdio: 'pipe' });
    return true;
  } catch {
    return false;
  }
}

function reportChanged(range, budgets) {
  const [base, headRaw] = parseRange(range);
  const head = headRaw || 'HEAD';
  const baseRef = new Ref(base);
  const headRef = new Ref(head === 'WORKTREE' ? null : head);

  if (!gitRefExists(base)) {
    console.error(`DEGRADED: base ref "${base}" is not available in this checkout.`);
    console.error('  The gate could not be evaluated — this is NOT a pass.');
    console.error('  On a shallow PR checkout the base must be fetched explicitly:');
    console.error(`    git fetch --no-tags --depth=1 origin ${base}`);
    console.error('  or compare against a ref that already exists locally.');
    process.exit(3);
  }
  if (!headRef.worktree && !gitRefExists(head)) {
    console.error(`DEGRADED: head ref "${head}" is not available in this checkout.`);
    console.error('  The gate could not be evaluated — this is NOT a pass.');
    process.exit(3);
  }

  const baseSurface = buildSurface(baseRef.reader);
  const headSurface = buildSurface(headRef.reader);
  if (surfaceSize(headSurface) === 0) {
    console.error(`DEGRADED: no API surface found at ${headRef.label}. Refusing to report a pass.`);
    process.exit(3);
  }

  const changed = changedFiles(base, head);
  if (!Array.isArray(changed)) {
    console.error(`DEGRADED: git diff failed for "${base}..${head}": ${changed.error}`);
    process.exit(3);
  }

  const docFiles = changed.filter((f) => f.startsWith(DOC_PREFIX) || DOC_EXTRA.has(f));
  const verdict = evaluate({ base: baseSurface, head: headSurface, docFiles, budgets });
  const report = {
    base: baseRef.label,
    head: headRef.label,
    surface: verdict.byLang,
    added: verdict.added,
    removed: verdict.removed,
    renameCandidates: verdict.renameCandidates,
    docFiles,
    docsChanged: verdict.docsChanged,
    llmsChanged: verdict.llmsChanged,
    failures: verdict.failures,
    pass: verdict.pass,
  };

  if (JSON_OUT) {
    console.log(JSON.stringify(report, null, 2));
  } else {
    console.log(`base${' '.repeat(17)}: ${baseRef.label}`);
    console.log(`head${' '.repeat(17)}: ${headRef.label}`);
    console.log('');
    console.log(printSurface(headSurface).join('\n'));
    console.log('');
    console.log(`${'files changed'.padEnd(21)}: ${changed.length}`);
    console.log(`${'docs/ files changed'.padEnd(21)}: ${verdict.docsChanged}`);
    console.log(`${'llms.txt changed'.padEnd(21)}: ${verdict.llmsChanged}`);
    if (docFiles.length) {
      console.log('');
      for (const f of docFiles.slice(0, 15)) console.log(`  doc  ${f}`);
      if (docFiles.length > 15) console.log(`  ... +${docFiles.length - 15} more`);
    }
    console.log('');
    const changedLangs = LANGUAGES.filter((l) => verdict.byLang[l.id].added || verdict.byLang[l.id].removed);
    if (!verdict.surfaceChanged) {
      console.log('OK: public API surface unchanged. Nothing to document.');
    } else {
      for (const l of changedLangs) {
        const v = verdict.byLang[l.id];
        console.log(
          `${l.label} surface changed: +${v.added} -${v.removed} (${v.base} -> ${v.head} items)`,
        );
        for (const e of v.addedEntries.slice(0, 12)) console.log(`  + ${e.replace(/\t/g, ' ')}`);
        if (v.addedEntries.length > 12) console.log(`  ... +${v.addedEntries.length - 12} more added`);
        for (const e of v.removedEntries.slice(0, 12)) console.log(`  - ${e.replace(/\t/g, ' ')}`);
        if (v.removedEntries.length > 12)
          console.log(`  ... +${v.removedEntries.length - 12} more removed`);
      }
      if (verdict.renameCandidates.length) {
        console.log('\nrename CANDIDATES (a name-only fingerprint cannot prove a rename):');
        for (const c of verdict.renameCandidates.slice(0, 10))
          console.log(`  ~ ${c.from}  ->  ${c.to}   (${c.kind})`);
      }
    }
    console.log('');
    for (const f of verdict.failures) {
      console.log(`GATE FAILED [${f.budget}]: ${f.message}`);
      console.log(`  ${f.count} surface change(s) > budget ${f.limit}`);
    }
    if (verdict.pass) {
      if (verdict.surfaceChanged) {
        console.log(
          verdict.llmsChanged
            ? 'OK: API surface changed and docs/ + llms.txt moved with it.'
            : 'OK: API surface changed and docs/ moved with it.',
        );
      }
    } else {
      console.log('');
      console.log('How to pass: change the code AND the docs in the same PR — see');
      console.log('docs/dev/workflow/gate-api-docs.md. To see what this job will say:');
      console.log(`  node scripts/docs/check-api-docs.mjs --changed ${base}..${head} --json`);
    }
  }
  process.exit(verdict.pass ? 0 : 1);
}

/** `--changed a..b` and `--changed a..` both parse; b defaults to HEAD. */
function parseRange(range) {
  const i = range.indexOf('..');
  if (i === -1) return [range, 'HEAD'];
  return [range.slice(0, i), range.slice(i + 2)];
}

// ---------------------------------------------------------------------- main

if (ARGS.includes('--self-test')) {
  process.exit(selfTest() ? 0 : 1);
}

const changedIdx = ARGS.findIndex((a) => a === '--changed' || a.startsWith('--changed='));
const apiIdx = ARGS.findIndex((a) => a === '--api-surface' || a.startsWith('--api-surface='));

if (changedIdx !== -1) {
  const inline = ARGS[changedIdx].startsWith('--changed=')
    ? ARGS[changedIdx].slice('--changed='.length)
    : ARGS[changedIdx + 1];
  if (!inline || inline.startsWith('--')) {
    console.error('usage: --changed <base>..<head>   (e.g. --changed origin/main..HEAD)');
    process.exit(2);
  }
  reportChanged(inline, {
    undocumented: UNDOCUMENTED_BUDGET,
    llmsStale: LLMS_STALE_BUDGET,
  });
} else if (apiIdx !== -1) {
  const inline = ARGS[apiIdx].startsWith('--api-surface=')
    ? ARGS[apiIdx].slice('--api-surface='.length)
    : ARGS[apiIdx + 1];
  reportSurface(inline && !inline.startsWith('--') ? inline : null);
} else {
  console.error(
    [
      'check-api-docs.mjs — public API surface vs documentation drift gate',
      '',
      '  --api-surface [ref]        print the normalized surface fingerprint',
      '  --changed <base>..<head>   gate: fail if the surface moved and docs did not',
      '                            (use WORKTREE as <head> for uncommitted changes)',
      '  --self-test                built-in assertions, synthetic fixtures only',
      '  --json                     machine-readable output',
      '  --max-undocumented=N       surface changes tolerated with no doc diff (default 0)',
      '  --max-llms-stale=N         tolerated when docs/ moved but llms.txt did not (default 0)',
      '',
      'exit: 0 ok · 1 gate failed · 2 bad usage · 3 degraded (could not evaluate)',
    ].join('\n'),
  );
  process.exit(2);
}
