// ------------------------------------------------------------------ ref reader

/**
 * A read-only view of the repository at one git ref.
 *
 * `new Ref(null)` reads the working tree from disk. `new Ref('HEAD~1')` reads
 * the committed tree via `git show` / `git ls-tree`. Neither ever checks out,
 * stashes, or writes anything: a gate that mutated the tree to look at history
 * would be a gate you could not trust to run twice.
 */
class Ref {
  constructor(ref) {
    this.ref = ref ?? null;
    this.worktree = this.ref === null;
    this.label = this.worktree ? 'WORKTREE' : this.ref;
    this._cache = new Map();
  }

  read = (rel) => {
    if (this._cache.has(rel)) return this._cache.get(rel);
    let out = null;
    try {
      out = this.worktree
        ? readFileSync(abs(rel), 'utf8')
        : execFileSync('git', ['show', `${this.ref}:${rel}`], {
            encoding: 'utf8',
            maxBuffer: 256 * 1024 * 1024,
            stdio: ['ignore', 'pipe', 'pipe'],
          });
    } catch {
      out = null; // path absent at this ref
    }
    this._cache.set(rel, out);
    return out;
  }

  /**
   * Fill the cache for many paths in ONE git process.
   *
   * `git show` costs a process spawn per file, and `src/` is ~500 files: the
   * per-file version of this took 21s on the reference checkout. `git cat-file
   * --batch` reads every blob over a single pipe, which brings the same work to
   * well under a second. Measured: 21s -> 0.3s for the whole Rust surface.
   */
  prefetch(paths) {
    const wanted = [...new Set(paths)].filter((p) => !this._cache.has(p));
    if (!wanted.length) return;
    if (this.worktree) {
      for (const p of wanted) {
        try {
          this._cache.set(p, readFileSync(abs(p), 'utf8'));
        } catch {
          this._cache.set(p, null);
        }
      }
      return;
    }
    let buf;
    try {
      buf = execFileSync('git', ['cat-file', '--batch'], {
        input: `${wanted.map((p) => `${this.ref}:${p}`).join('\n')}\n`,
        // No `encoding` (or null) is what returns a Buffer. `'buffer'` is not a
        // valid Node encoding and throws, which silently fell back to per-file
        // `git show` and put this back at 21s.
        encoding: null,
        maxBuffer: 512 * 1024 * 1024,
        stdio: ['pipe', 'pipe', 'pipe'],
      });
    } catch {
      return; // fall back to per-file `git show`
    }
    let pos = 0;
    for (const p of wanted) {
      const nl = buf.indexOf(10, pos);
      if (nl === -1) break;
      const header = buf.toString('utf8', pos, nl);
      pos = nl + 1;
      const size = Number(header.split(' ')[2]);
      if (header.endsWith(' missing') || !Number.isFinite(size)) {
        this._cache.set(p, null);
        continue;
      }
      this._cache.set(p, buf.toString('utf8', pos, pos + size));
      pos += size + 1; // the LF git writes after the blob body
    }
  }

  exists(rel) {
    if (this.worktree) return existsSync(abs(rel));
    return this.read(rel) !== null;
  }

  /**
   * The same object, shaped as a plain reader. A class field cannot be
   * destructured as a bare function, and `buildSurface` takes a reader — so one
   * `get reader()` keeps Ref usable as both the object and the function.
   */
  get reader() {
    return { read: this.read, list: this.list.bind(this), prefetch: this.prefetch.bind(this) };
  }

  /** Repo-relative POSIX paths of every file under `prefix` at this ref. */
  list(prefix) {
    const prefixSlash = prefix.endsWith('/') ? prefix : `${prefix}/`;
    if (this.worktree) {
      const out = [];
      const rootDir = abs(prefixSlash);
      if (!existsSync(rootDir)) return out;
      (function walk(dir) {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
          const full = join(dir, e.name);
          if (e.isDirectory()) walk(full);
          else if (statSync(full).isFile()) out.push(toPosix(full.slice(ROOT.length + 1)));
        }
      })(rootDir);
      return out.sort();
    }
    try {
      return execFileSync('git', ['ls-tree', '-r', '--name-only', this.ref, '--', prefixSlash], {
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
        stdio: ['ignore', 'pipe', 'pipe'],
      })
        .split('\n')
        .map((s) => s.trim())
        .filter(Boolean);
    } catch {
      return [];
    }
  }
}

/** git diff --name-only, with the usual git-failure reasons turned into text. */
function changedFiles(baseRef, headRef) {
  const args = ['diff', '--name-only'];
  if (headRef === 'WORKTREE') {
    if (baseRef === 'HEAD') {
      // uncommitted only
      args.push('HEAD');
    } else {
      args.push(baseRef);
    }
  } else {
    args.push(baseRef, headRef);
  }
  try {
    return execFileSync('git', args, {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'pipe'],
    })
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean);
  } catch (e) {
    const stderr = (e.stderr ?? '').toString().trim().split('\n')[0] ?? '';
    return { error: stderr || e.message };
  }
}

// ------------------------------------------------------------- rust extractor

// ponytail: static parse, not a compiler. Captures NAMES and KINDS of reachable
// pub items; it does not resolve macro-generated items, `include!`, cfg-gated
// items behind default-off features, or generic arity. Signature-level fidelity
// is the `public-api` snapshot's job (tests/api/public_api.rs), not this file's.

const RUST_MODULE_DEPTH = 4; // crate root + 4 nested levels is the real shape
const RUST_FILE_CAP = 4000; // hard stop; src/ is ~1000 files and never grows past this

/** Strip comments and string literals so a `pub` inside them is not an item. */
function stripRust(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/\/\/[^\n]*/g, '');
}

const rustFileFor = (modPath) =>
  modPath === ''
    ? 'src/lib.rs'
    : `src/${modPath.replace(/::/g, '/')}.rs`.endsWith('.rs') &&
      // prefer foo.rs, fall back to foo/mod.rs — callers try both
      `src/${modPath.replace(/::/g, '/')}.rs`;

const lastSegment = (path) => (path.includes('::') ? path.slice(path.lastIndexOf('::') + 2) : path);

function qualify(name, prefix) {
  const tail = lastSegment(name);
  const clean = tail.replace(/^crate::/, '');
  if (prefix && !name.includes('::')) return `${prefix}::${clean}`;
  if (prefix && clean.startsWith(`${prefix}::`)) return clean;
  return clean;
}

/**
 * Every extractor takes the same reader object — the `Ref` interface
 * `{ read(rel) -> string|null, list(prefix) -> string[] }` — so a live working
 * tree and a `git show` at a ref are interchangeable, and the self-test can
 * pass a literal without learning about git.
 */
function extractRust(reader) {
  const { read } = reader;
  // One batched read of the whole crate: the walk below discovers paths
  // incrementally, and a per-file `git show` would cost one process per module.
  if (reader.prefetch && reader.list) {
    reader.prefetch(['src/lib.rs', ...reader.list('src').filter((p) => p.endsWith('.rs'))]);
  } else if (reader.prefetch) {
    reader.prefetch(['src/lib.rs']);
  }
  if (!read('src/lib.rs')) return [];
  const out = new Set();
  const seen = new Set();
  const queue = [''];
  let filesRead = 0;

  while (queue.length && filesRead < RUST_FILE_CAP) {
    const prefix = queue.shift();
    if (seen.has(prefix)) continue;
    seen.add(prefix);
    const rel = prefix
      ? `src/${prefix.replace(/::/g, '/')}.rs`
      : 'src/lib.rs';
    const modFile = read(rel) ?? read(`src/${prefix.replace(/::/g, '/')}/mod.rs`);
    if (modFile == null) continue;
    filesRead++;
    const text = stripRust(modFile);
    const q = (n) => (prefix ? `${prefix}::${n}` : n);

    for (const m of text.matchAll(/^[ \t]*pub\s+mod\s+([A-Za-z_]\w*)\s*(?::\s*pub)?\s*;/gm)) {
      const name = q(m[1]);
      out.add(`rust\tmod\t${name}`);
      if (prefix.split('::').length < RUST_MODULE_DEPTH) queue.push(name);
    }

    for (const m of text.matchAll(/^pub\s+(?:async\s+)?(?:const\s+)?(?:unsafe\s+)?(?:extern\s+"[^"]*"\s+)?fn\s+([A-Za-z_]\w*)/gm)) {
      out.add(`rust\tfn\t${q(m[1])}`);
    }
    for (const m of text.matchAll(/^pub\s+(struct|enum|trait|union)\s+([A-Za-z_]\w*)/gm)) {
      out.add(`rust\t${m[1]}\t${q(m[2])}`);
    }
    for (const m of text.matchAll(/^pub\s+type\s+([A-Za-z_]\w*)/gm)) {
      out.add(`rust\ttype\t${q(m[1])}`);
    }
    for (const m of text.matchAll(/^pub\s+(?:const|static)\s+(?:mut\s+)?([A-Za-z_]\w*)/gm)) {
      out.add(`rust\tconst\t${q(m[1])}`);
    }

    // crate-root (and module) re-exports: the names docs actually use. A
    // re-export's public name is always its LAST path segment, so
    // `pub use sdk::GroupByConfig` and `pub use sdk::{GroupByConfig, ..}` are
    // the same name. Keeping the source module would record one surface item
    // twice and make an unrelated module move look like an API change.
    for (const m of text.matchAll(/(?:^|[\s;])pub\s+use\s+([^;]+);/g)) {
      for (const n of flattenUse(m[1], prefix)) out.add(`rust\treexport\t${lastSegment(n)}`);
    }

    // inherent impl methods. `impl Trait for Type` keeps Type; a column-0 `}`
    // leaves the block.
    let implType = null;
    for (const line of text.split('\n')) {
      if (/^\}/.test(line)) {
        implType = null;
        continue;
      }
      const h = line.match(/^[ \t]*impl(?:<[^>]*>)?[ \t]+(.+?)[ \t]*\{[ \t]*$/);
      if (h) {
        let head = h[1];
        if (head.includes(' for ')) head = head.slice(head.lastIndexOf(' for ') + 5);
        const ty = head.trim().split(/[\s<>,(&)]/)[0];
        if (!ty) continue;
        implType = ty.startsWith('crate::') ? ty.slice(7) : qualify(ty, prefix);
        out.add(`rust\timpl\t${implType}`);
        continue;
      }
      const fn = line.match(
        /^[ \t]+pub(?:\([^)]*\))?[ \t]+(?:async[ \t]+)?(?:const[ \t]+)?(?:unsafe[ \t]+)?(?:extern[ \t]+"[^"]*"[ \t]+)?fn[ \t]+([A-Za-z_]\w*)/,
      );
      if (fn && implType) out.add(`rust\tmethod\t${implType}::${fn[1]}`);
    }
  }
  return [...out].sort();
}

/** `a::{B, c::{D as E}}` -> [a::B? no: B, E] — public re-export names only. */
function flattenUse(clause, prefix) {
  const s = clause.trim();
  const bi = s.indexOf('{');
  if (bi === -1) {
    const as = s.split(/\s+as\s+/);
    return [qualify((as[1] ?? as[0]).trim(), prefix)];
  }
  const head = s.slice(0, bi).replace(/:\s*$/, '').trim();
  const close = s.lastIndexOf('}');
  const body = s.slice(bi + 1, close === -1 ? s.length : close);
  const out = [qualify(head, prefix)];
  for (const part of splitTopLevel(body)) {
    if (part.trim()) out.push(...flattenUse(part, prefix));
  }
  return out;
}

/** Split on commas that are not inside nested braces. */
function splitTopLevel(body) {
  const out = [];
  let depth = 0;
  let cur = '';
  for (const ch of body) {
    if (ch === '{') depth++;
    if (ch === '}') depth--;
    if (ch === ',' && depth === 0) {
      out.push(cur);
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out;
}

// ---------------------------------------------------------- python extractor

const PY_FILES = [
  // native extension stub — the compiled module's declared surface
  'vantadb-python/vantadb_py/vantadb_py.pyi',
  // pure-Python wrapper: adds SearchRequest / AsyncClient, re-exports the rest
  'vantadb-python/vantadb_py/__init__.pyi',
  'vantadb-python/vantadb_py/__init__.py',
  // canonical `import vantadb` alias
  'vantadb-python/vantadb/__init__.py',
];

const PY_CLASS_RE = /^class\s+([A-Za-z_]\w*)\s*(?:\(([^)]*)\))?\s*:/;
const PY_FN_RE = /^(?:async\s+)?def\s+([A-Za-z_]\w*)\s*\(/;
// `name: T`  — a declared attribute, with no assignment part.
const PY_ANNOT_RE = /^([A-Za-z_]\w*)\s*:\s*[^=]+$/;
// `name = ...` or `name: T = ...` — a module-level binding with a value.
const PY_BIND_RE = /^([A-Za-z_]\w*)\s*(?::[^=]+)?=\s*\S/;
const PY_ALL_RE = /^__all__\s*=\s*\[([\s\S]*?)\]/m;

/**
 * Read a `.pyi`/`.py` file as a declaration list.
 *
 * Triple-quoted docstrings are skipped: this repo writes long ones that contain
 * `def` and `class` examples, and an example in a docstring is not a member.
 */
function parsePythonSource(text, out, { module = '', stubs = false } = {}) {
  let cls = null;
  let clsIndent = -1;
  let fnIndent = -1; // inside a def body: implementation, not surface
  let inDoc = null;
  const q = (n) => (module ? `${module}::${n}` : n);

  for (const raw of text.split('\n')) {
    const line = raw.trimEnd();
    const indent = (line.match(/^ */) ?? [''])[0].length;

    if (inDoc) {
      if (line.includes(inDoc)) inDoc = null;
      continue;
    }
    const openDoc = line.match(/^[rbuf]{0,2}("""|''')/);
    if (openDoc) {
      if (!line.slice(line.indexOf(openDoc[1]) + 3).includes(openDoc[1])) inDoc = openDoc[1];
      continue;
    }
    if (!line.trim()) continue;

    // Inside a def body: that is implementation, not surface. `self._run = run`
    // in AsyncClient.__init__ is a local, not a property of AsyncClient.
    if (fnIndent >= 0) {
      if (indent > fnIndent) continue;
      fnIndent = -1;
    }

    const all = line.match(PY_ALL_RE);
    if (all) {
      for (const n of parseAllList(all[1])) out.add(`python\treexport\t${n}`);
      continue;
    }
    if (line.trimStart().startsWith('#')) continue;

    const c = line.trim().match(PY_CLASS_RE);
    if (c) {
      cls = q(c[1]);
      clsIndent = indent;
      out.add(`python\tclass\t${cls}`);
      continue;
    }
    if (cls !== null && indent <= clsIndent) {
      cls = null;
      clsIndent = -1;
    }

    const body = line.trim();
    const f = body.match(PY_FN_RE);
    if (f && isPublicName(f[1])) {
      // A real def has a body; a stub def is `...` on the same line. Only the
      // former opens an implementation scope worth skipping.
      if (!stubs) fnIndent = indent;
      out.add(`python\t${cls ? 'method' : 'fn'}\t${cls ? `${cls}::${f[1]}` : q(f[1])}`);
      continue;
    }
    if (f) continue; // _private by convention; a dunder def is handled above
    if (/^@/.test(body)) continue; // decorator, the def/class follows
    if (/^(if|for|while|return|import|from|with|try|except|raise|assert)\b/.test(body)) continue;

    const annot = body.match(PY_ANNOT_RE);
    const bind = annot ? null : body.match(PY_BIND_RE);
    const name = (annot ?? bind)?.[1];
    if (!name || name === '__all__' || !isPublicName(name)) continue;
    out.add(`python\t${cls ? 'property' : 'const'}\t${cls ? `${cls}::${name}` : q(name)}`);
  }
}

/**
 * Public by Python's own convention, which distinguishes three cases the docs
 * care about differently:
 *   `get`      public
 *   `_run`     private by convention
 *   `__x`      name-mangled private (class-private), still surface-adjacent
 *   `__len__`  dunder — the DOCUMENTED protocol surface (len(), [], iteration)
 * so dunders count and everything else underscore-prefixed does not.
 */
const isPublicName = (n) => !n.startsWith('_') || (n.startsWith('__') && n.endsWith('__'));

/** `["A", "B",]` -> [A, B] */
function parseAllList(body) {
  return body
    .split(',')
    .map((s) => s.trim().replace(/^["']|["']$/g, ''))
    .filter((s) => /^[A-Za-z_]\w*$/.test(s));
}

function extractPython(reader) {
  const { read } = reader;
  reader.prefetch?.(PY_FILES);
  const out = new Set();
  for (const rel of PY_FILES) {
    const text = read(rel);
    if (text == null) continue;
    parsePythonSource(text, out, { stubs: rel.endsWith('.pyi') });
  }
  return [...out].sort();
}

// ------------------------------------------------------------- typescript

const TS_DIR = 'vantadb-ts/src';

const TS_EXPORT_RE =
  /^export\s+(?:declare\s+)?(?:default\s+)?(abstract\s+)?(async\s+)?(class|interface|enum|function|const|let|type|namespace)\s+([A-Za-z_$][\w$]*)/;

function extractTs(reader) {
  const { read, list } = reader;
  const out = new Set();
  const files = list(TS_DIR)
    .filter((p) => p.endsWith('.ts') && !p.endsWith('.d.ts'))
    .filter((p) => !p.includes('/__tests__/') && !p.includes('/node_modules/'))
    .sort();
  reader.prefetch?.(files);

  for (const rel of files) {
    const text = read(rel);
    if (text == null) continue;
    const lines = text.split('\n');

    let blockKind = null; // { kind, name, indent }
    let objLiteral = null; // { name, indent } for `export const X = {`

    for (const raw of lines) {
      const indent = (raw.match(/^ */) ?? [''])[0].length;
      const line = raw.trim();

      if (blockKind) {
        if (indent <= blockKind.indent && line.startsWith('}')) {
          blockKind = null;
          continue;
        }
        if (line.startsWith('}') && indent === blockKind.indent) {
          blockKind = null;
          continue;
        }
        if (blockKind.kind === 'class') tsClassMember(line, out, blockKind.name);
        else if (blockKind.kind === 'interface') tsIfaceMember(line, out, blockKind.name);
        else if (blockKind.kind === 'enum') {
          const k = line.match(/^([A-Za-z_$][\w$]*)\s*(?:=|,|$)/);
          if (k) out.add(`ts\tvariant\t${blockKind.name}::${k[1]}`);
        }
        continue;
      }
      if (objLiteral) {
        if (indent <= objLiteral.indent && line.startsWith('}')) {
          objLiteral = null;
          continue;
        }
        const k = line.match(/^['"]?([A-Za-z_$][\w$]*)['"]?\s*[,:]/);
        if (k && !line.startsWith('//')) out.add(`ts\tproperty\t${objLiteral.name}::${k[1]}`);
        continue;
      }
      if (!line || line.startsWith('//') || line.startsWith('*') || line.startsWith('/*')) continue;

      const ex = line.match(TS_EXPORT_RE);
      if (ex) {
        const kind = ex[3];
        const name = ex[4];
        if (kind === 'function') out.add(`ts\tfn\t${name}`);
        else if (kind === 'type') out.add(`ts\ttype\t${name}`);
        else if (kind === 'const' || kind === 'let') {
          out.add(`ts\tconst\t${name}`);
          if (/=\s*\{\s*$/.test(line)) objLiteral = { name, indent };
        } else {
          const open = new RegExp(`^[ \\t]*(?:export\\s+)?(?:declare\\s+)?${kind}\\b[^;{]*\\{`);
          if (open.test(line)) blockKind = { kind, name, indent };
          out.add(`ts\t${kind}\t${name}`);
        }
        continue;
      }
      const reexport = line.match(/^export\s*\{([^}]*)\}/);
      if (reexport) {
        for (const n of reexport[1].split(',')) {
          const nm = n.trim().split(/\s+as\s+/).pop();
          if (nm && /^[A-Za-z_$][\w$]*$/.test(nm)) out.add(`ts\treexport\t${nm}`);
        }
      }
    }
  }
  return [...out].sort();
}

/** Class member: skips private/protected, records methods and properties. */
function tsClassMember(line, out, cls) {
  if (!line || line.startsWith('//') || line.startsWith('*') || line.startsWith('/*')) return;
  if (/^(private|protected|declare)\b/.test(line)) return;
  if (line.startsWith('#')) return;
  if (/^(constructor|static\s*\{)/.test(line)) return;
  const acc = line.match(
    /^(?:static\s+|readonly\s+|override\s+|abstract\s+|async\s+|declare\s+)*(?:(get|set)\s+)?([A-Za-z_$][\w$]*)\s*([(<:]|\?|=|;|$)/,
  );
  if (!acc) return;
  // A member is a method only when it actually opens a signature or a type
  // parameter list. `readonly version = 1` opens neither, so it is a field.
  const kind = acc[1] ? 'property' : acc[3] === '(' || acc[3] === '<' ? 'method' : 'property';
  out.add(`ts\t${kind}\t${cls}::${acc[2]}`);
}

/** Interface member: a call signature is a method, anything else a property. */
function tsIfaceMember(line, out, iface) {
  if (!line || line.startsWith('//') || line.startsWith('*') || line.startsWith('/*')) return;
  if (line.startsWith('[') || line.startsWith('(')) return; // index/call signature
  const m = line.match(/^(?:readonly\s+)?([A-Za-z_$][\w$]*)\??\s*(<[^>]*>)?\s*(\(|:)/);
  if (!m) return;
  out.add(`ts\t${m[3] === '(' ? 'method' : 'property'}\t${iface}::${m[1]}`);
}

// ------------------------------------------------------------------ surface

const LANGUAGES = [
  { id: 'rust', label: 'rust', extract: extractRust },
  { id: 'python', label: 'python', extract: extractPython },
  { id: 'ts', label: 'ts', extract: extractTs },
];

/** @returns {Map<string,string[]>} lang -> sorted entries */
export function buildSurface(read) {
  const surface = new Map();
  for (const l of LANGUAGES) {
    const entries = [...new Set(l.extract(read))].sort();
    surface.set(l.id, entries);
  }
  return surface;
}

export function surfaceSize(surface) {
  let n = 0;
  for (const entries of surface.values()) n += entries.length;
  return n;
}

/**
 * added / removed, plus rename CANDIDATES.
 *
 * A rename is not detectable from a name-and-kind fingerprint: removing
 * `foo` and adding `bar` of the same kind is byte-identical to a delete plus
 * an unrelated add. So this is reported as a heuristic — a same-kind
 * remove/add pair that is the ONLY churn of that kind — and the report says
 * "candidates", never "renamed".
 */
export function diffSurfaces(base, head) {
  const added = [];
  const removed = [];
  const byLang = {};
  for (const { id } of LANGUAGES) {
    const b = base.get(id) ?? [];
    const h = head.get(id) ?? [];
    const bSet = new Set(b);
    const hSet = new Set(h);
    const a = h.filter((e) => !bSet.has(e));
    const r = b.filter((e) => !hSet.has(e));
    byLang[id] = {
      base: b.length,
      head: h.length,
      added: a.length,
      removed: r.length,
      addedEntries: a,
      removedEntries: r,
    };
    added.push(...a);
    removed.push(...r);
  }
  return { added, removed, byLang, renameCandidates: renameCandidates(added, removed) };
}

function renameCandidates(added, removed) {
  const byKind = (list) => {
    const m = new Map();
    for (const e of list) {
      const [, kind] = e.split('\t');
      m.set(kind, (m.get(kind) ?? 0) + 1);
    }
    return m;
  };
  const a = byKind(added);
  const r = byKind(removed);
  const out = [];
  for (const [kind, n] of r) {
    if (a.get(kind) === n && n > 0) {
      for (const e of removed.filter((x) => x.split('\t')[1] === kind)) {
        for (const f of added.filter((x) => x.split('\t')[1] === kind)) {
          out.push({ kind, from: e.split('\t')[2], to: f.split('\t')[2] });
        }
      }
    }
  }
  return out;
}

// --------------------------------------------------------------------- gate

/**
 * The whole rule, as one pure function so --self-test exercises the real path
 * rather than a paraphrase of it.
 */
export function evaluate({ base, head, docFiles = [], budgets = {} }) {
  const undoc = budgets.undocumented ?? UNDOCUMENTED_BUDGET;
  const llmsStale = budgets.llmsStale ?? LLMS_STALE_BUDGET;
  const diff = diffSurfaces(base, head);
  const surfaceChanged = diff.added.length + diff.removed.length > 0;

  const docsChanged = docFiles.some((f) => f.startsWith(DOC_PREFIX));
  const llmsChanged = docFiles.some((f) => DOC_EXTRA.has(f));
  const docTouched = docsChanged || llmsChanged;

  const failures = [];
  if (surfaceChanged && !docTouched && diff.added.length + diff.removed.length > undoc) {
    failures.push({
      budget: 'undocumented',
      limit: undoc,
      count: diff.added.length + diff.removed.length,
      message:
        `public API surface changed (${diff.added.length} added, ${diff.removed.length} removed) ` +
        'and NOTHING under docs/ or llms.txt changed',
    });
  }
  if (surfaceChanged && docsChanged && !llmsChanged && diff.added.length + diff.removed.length > llmsStale) {
    failures.push({
      budget: 'llms-stale',
      limit: llmsStale,
      count: diff.added.length + diff.removed.length,
      message:
        `public API surface changed and docs/ changed, but llms.txt did not ` +
        `(llms.txt is generated from frontmatter by gen-index.mjs and is what AI agents read)`,
    });
  }
  return {
    ...diff,
    surfaceChanged,
    docsChanged,
    llmsChanged,
    docTouched,
    docFiles,
    failures,
    pass: failures.length === 0,
  };
}

